function getLang() {
  return (window.MAZZA_STATE && window.MAZZA_STATE.lang) || localStorage.getItem('mazza_lang') || 'uz';
}

function t(key) {
  const lang = getLang();
  const dict = window.MAZZA_I18N[lang] || window.MAZZA_I18N.uz;
  return dict[key] || window.MAZZA_I18N.uz[key] || key;
}

function langField(obj, baseField) {
  if (!obj) return '';
  const lang = getLang();
  const suffix = lang === 'ru' ? 'Ru' : 'Uz';
  const fallbackSuffix = lang === 'ru' ? 'Uz' : 'Ru';
  return obj[`${baseField}${suffix}`] || obj[`${baseField}${fallbackSuffix}`] || '';
}

function formatPrice(value) {
  const num = Math.round(Number(value) || 0);
  return `${num.toString().replace(/\B(?=(\d{3})+(?!\d))/g, ' ')} ${t('currency')}`;
}

function getStatusLabel(status) {
  return t(`status_${status}`) || status;
}

function applyStaticTranslations() {
  const lang = getLang();
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.setAttribute('placeholder', t(key));
  });
  document.querySelectorAll('.lang-btn, .lang-btn-mobile').forEach((btn) => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });
}

window.t = t;
window.langField = langField;
window.formatPrice = formatPrice;
window.getStatusLabel = getStatusLabel;
window.applyStaticTranslations = applyStaticTranslations;
